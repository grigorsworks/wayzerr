// Builds the light theme from the dark stylesheet: every rule that sets a colour gets a
// "html.light" copy with the colour flipped (dark surfaces → light, light text → dark).
// Run: NODE_PATH=/tmp/pc/node_modules node scripts/make-light.js <in.css> <out.css> <vars.css>
const fs = require('fs');
const postcss = require('postcss');
const [,, IN, OUT, VARSFILE, SCOPE = 'html.light'] = process.argv;

const hex2rgb = (h) => { h = h.slice(1); if (h.length === 3) h = [...h].map((c) => c + c).join(''); const n = parseInt(h, 16); return [n >> 16, (n >> 8) & 255, n & 255]; };
const rgb2hex = (r, g, b) => '#' + [r, g, b].map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('');
function rgb2hsl(r, g, b) { r /= 255; g /= 255; b /= 255; const mx = Math.max(r, g, b), mn = Math.min(r, g, b); let h = 0, s = 0; const l = (mx + mn) / 2; if (mx !== mn) { const d = mx - mn; s = l > .5 ? d / (2 - mx - mn) : d / (mx + mn); h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; h /= 6; } return [h, s, l]; }
function hsl2rgb(h, s, l) { if (!s) return [l * 255, l * 255, l * 255]; const q = l < .5 ? l * (1 + s) : l + s - l * s, p = 2 * l - q; const f = (t) => { t = (t + 1) % 1; return 255 * (t < 1 / 6 ? p + (q - p) * 6 * t : t < .5 ? q : t < 2 / 3 ? p + (q - p) * (2 / 3 - t) * 6 : p); }; return [f(h + 1 / 3), f(h), f(h - 1 / 3)]; }
// Dark UI colour → light UI colour.
function flipHex(hex) {
  const [r, g, b] = hex2rgb(hex); const [h, s, l] = rgb2hsl(r, g, b);
  const neutral = s < .22 || l < .2;
  if (!(neutral || l < .3 || l > .76)) return hex; // bright brand/accent colours stay
  let L = 1 - l * .9;
  if (l > .76 && !neutral) L = Math.max(.28, 1 - l); // light accent text → darker shade
  return rgb2hex(...hsl2rgb(h, neutral ? Math.min(s, .12) : s, L));
}
function flipRgba(m) {
  const p = m.slice(m.indexOf('(') + 1, -1).split(',').map((x) => x.trim());
  const [r, g, b] = p.map(Number); const a = p[3] ?? '1';
  if (r === 255 && g === 255 && b === 255) return `rgba(0,0,0,${a})`;
  if (r === 0 && g === 0 && b === 0) return m; // shadows / dimming stay dark
  if (r === 10 && g === 10 && b === 10) return `rgba(255,255,255,${a})`;
  return m;
}
const COLOR = /#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\)/g;
const flip = (v) => v.replace(COLOR, (m) => (m[0] === '#' ? flipHex(m) : flipRgba(m)));
const SKIP_PROP = /^(-webkit-)?mask|shadow$|^filter$|^accent-color$/;
const SKIP_SEL = /(^|[\s,])(\.logo|\.ph-qr|#fs-slot|\.fs-ghost|\.char|\.c-(fx|swirl|sparkles|trail|dots|slab|ground)|\.bot-img|\.iv-[a-z-]+|\.ivf|img)\b/;
const SATURATED_BG = (rule) => rule.nodes.some((d) => d.type === 'decl' && /^background/.test(d.prop) && ((d.value.match(/#[0-9a-fA-F]{3,6}\b/g) || []).some((h) => { const [, s, l] = rgb2hsl(...hex2rgb(h)); return s > .35 && l > .3 && l < .76; }) || /rgba\(0,\s*0,\s*0,\s*\.[3-9]/.test(d.value)));

const root = postcss.parse(fs.readFileSync(IN, 'utf8'));
const out = postcss.root();
root.walkRules((rule) => {
  if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  if (SKIP_SEL.test(rule.selector)) return;
  const keepWhiteText = SATURATED_BG(rule);
  const decls = [];
  rule.each((d) => {
    if (d.type !== 'decl' || SKIP_PROP.test(d.prop) || d.prop.startsWith('--') && rule.selector === ':root') return;
    if (!COLOR.test(d.value)) return; COLOR.lastIndex = 0;
    if (keepWhiteText && d.prop === 'color') return;
    const v = flip(d.value);
    if (v !== d.value) decls.push(postcss.decl({ prop: d.prop, value: v, important: d.important }));
  });
  if (!decls.length) return;
  const sel = rule.selectors.map((s) => (/^(html|:root)\b/.test(s) ? s.replace(/^(html|:root)/, SCOPE) : `${SCOPE} ${s}`)).join(',\n');
  const r = postcss.rule({ selector: sel }); decls.forEach((d) => r.append(d));
  if (rule.parent.type === 'atrule') { const at = postcss.atRule({ name: rule.parent.name, params: rule.parent.params }); at.append(r); out.append(at); }
  else out.append(r);
});
const VARS = VARSFILE && fs.existsSync(VARSFILE) ? fs.readFileSync(VARSFILE, 'utf8') : '';
fs.writeFileSync(OUT, '/* Light theme — generated by scripts/make-light.js from the dark styles. */\n' + out.toString() + '\n' + VARS);
console.log('light rules:', out.nodes.length);
